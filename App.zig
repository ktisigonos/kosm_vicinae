//! A Vicinae theme of its own, generated whole, which the app also selects in Vicinae's
//! settings along with the font. Field names are Vicinae's.

const App = @This();

const std = @import("std");
const kosm = @import("kosm");

/// The theme file kosm owns. Vicinae names a theme by its file name without `.toml`.
/// Default: `~/.local/share/vicinae/themes/kosm.toml`.
file: []const u8 = "~/.local/share/vicinae/themes/kosm.toml",
/// Vicinae's settings, where the app selects the theme (`theme.dark.name` or `theme.light.name`,
/// by `meta.variant`) and sets the font fields that are set; those keys must be there already.
/// null: the settings are not touched. Default: `~/.config/vicinae/settings.json`.
settings: ?[]const u8 = "~/.config/vicinae/settings.json",
/// `[meta]`: how Vicinae lists the theme.
meta: Meta = .{},
/// `[colors]`.
colors: Colors = .{},
/// `font.normal.family` in the settings. null: left as it is.
font_family: ?[]const u8 = null,
/// `font.normal.size` in the settings, in points. null: left as it is.
font_size: ?f64 = null,

/// A theme's `[colors]`.
pub const Colors = @import("Colors.zig");

/// `[meta]`.
pub const Meta = struct {
    /// The name Vicinae shows. Default: `kosm`.
    name: []const u8 = "kosm",
    /// A line describing the theme. Default: `Generated by kosm`.
    description: []const u8 = "Generated by kosm",
    /// Whether the theme is dark or light, which picks icons and the settings key it is
    /// selected under. `from`: the theme's mode. Default: `.dark`.
    variant: Variant = .dark,
    /// The theme colors left null come from. null: Vicinae's default for the variant.
    inherits: ?[]const u8 = null,
};

/// A theme's variant.
pub const Variant = enum { dark, light };

/// Colors from the theme: the core from black, white and cyan (the accent), the accents from
/// the wheel, muted text and selections from the theme's variations. The rest Vicinae derives
/// from the core.
pub fn from(theme: kosm.Theme) App {
    const palette = theme.palette;
    const variations = theme.variations;
    const foreground = if (theme.mode == .dark) palette.white else palette.black;
    const background = if (theme.mode == .dark) palette.black else palette.white;
    const raised = variations.state.selected.apply(background);
    return .{
        .meta = .{ .variant = if (theme.mode == .dark) .dark else .light },
        .colors = .{
            .core = .{
                .accent = palette.cyan,
                .accent_foreground = background,
                .background = background,
                .foreground = foreground,
                .secondary_background = raised,
                .border = palette.cyan,
            },
            .accents = .{
                .blue = palette.blue,
                .green = palette.green,
                .magenta = palette.magenta,
                .orange = palette.orange,
                .red = palette.red,
                .yellow = palette.yellow,
                .cyan = palette.cyan,
                .purple = palette.purple,
            },
            .text = .{
                .muted = variations.emphasis.muted.apply(foreground),
                .danger = palette.red,
                .success = palette.green,
                .selection = .{ .background = foreground, .foreground = background },
            },
            .list = .{ .item = .{ .selection = .{
                .background = raised,
                .foreground = variations.emphasis.strong.apply(foreground),
            } } },
        },
    };
}

/// Writes the theme whole, then selects it and sets the font in `settings` unless it is null.
pub fn apply(self: App, output: *kosm.Output) !void {
    const theme_name = std.Io.Dir.path.stem(self.file);
    if (!std.mem.eql(u8, std.Io.Dir.path.extension(self.file), ".toml") or theme_name.len == 0)
        return output.fail(self.file, "Vicinae reads themes only from '.toml' files", .{});
    var meta: std.ArrayList(kosm.Value.Entry) = .empty;
    try meta.appendSlice(output.allocator, &.{
        .{ .key = "name", .value = .{ .string = self.meta.name } },
        .{ .key = "description", .value = .{ .string = self.meta.description } },
        .{ .key = "variant", .value = .{ .string = @tagName(self.meta.variant) } },
    });
    if (self.meta.inherits) |inherits| try meta.append(output.allocator, .{ .key = "inherits", .value = .{ .string = inherits } });
    var sections: std.ArrayList(kosm.Value.Entry) = .empty;
    try sections.append(output.allocator, .{ .key = "meta", .value = .{ .table = meta.items } });
    if (try colorTable(output.allocator, self.colors)) |colors| try sections.append(output.allocator, .{ .key = "colors", .value = colors });
    try output.generate(.{ .file = self.file, .lang = "toml" }, kosm.Value{ .table = sections.items });
    const settings_file = self.settings orelse return;
    var settings = try output.edit(.{ .files = settings_file, .lang = "jsonc" });
    const selected: []const u8 = switch (self.meta.variant) {
        .dark => "theme.dark.name",
        .light => "theme.light.name",
    };
    try settings.set(selected, theme_name);
    if (self.font_family) |family| try settings.set("font.normal.family", family);
    if (self.font_size) |size| try settings.set("font.normal.size", size);
}

/// The set colors of a section and the sections inside it, by field name; null when none is set,
/// so empty sections are not written.
fn colorTable(allocator: std.mem.Allocator, section: anytype) std.mem.Allocator.Error!?kosm.Value {
    var entries: std.ArrayList(kosm.Value.Entry) = .empty;
    inline for (@typeInfo(@TypeOf(section)).@"struct".field_names) |name| {
        const field = @field(section, name);
        const value: ?kosm.Value = if (@TypeOf(field) == ?kosm.Color)
            if (field) |color| .{ .color = color } else null
        else
            try colorTable(allocator, field);
        if (value) |present| try entries.append(allocator, .{ .key = name, .value = present });
    }
    return if (entries.items.len == 0) null else .{ .table = entries.items };
}

const testing = std.testing;
const root = @import("root.zig");

const Fixture = struct {
    tmp: testing.TmpDir,
    arena: std.heap.ArenaAllocator,
    plan: kosm.Plan,
    diagnostics: kosm.Diagnostics = .{},
    warnings: kosm.Warnings = undefined,
    home_buffer: [std.Io.Dir.max_path_bytes]u8 = undefined,
    output: kosm.Output = undefined,

    fn init(fixture: *Fixture, settings: ?[]const u8) !void {
        fixture.* = .{ .tmp = testing.tmpDir(.{}), .arena = .init(testing.allocator), .plan = .init(testing.allocator, testing.io) };
        if (settings) |text| {
            try fixture.tmp.dir.createDirPath(testing.io, ".config/vicinae");
            try fixture.tmp.dir.writeFile(testing.io, .{ .sub_path = ".config/vicinae/settings.json", .data = text });
        }
        fixture.warnings = .init(fixture.arena.allocator());
        const length = try fixture.tmp.dir.realPath(testing.io, &fixture.home_buffer);
        fixture.output = .{
            .allocator = fixture.arena.allocator(),
            .home = fixture.home_buffer[0..length],
            .adapters = &.{ root.toml_adapter, root.jsonc_adapter },
            .plan = &fixture.plan,
            .diagnostics = &fixture.diagnostics,
            .warnings = &fixture.warnings,
            .app = "vicinae",
        };
    }

    fn deinit(fixture: *Fixture) void {
        fixture.plan.deinit();
        fixture.arena.deinit();
        fixture.tmp.cleanup();
    }

    fn planned(fixture: *Fixture, display_path: []const u8) []const u8 {
        for (fixture.plan.files.items) |file| {
            if (std.mem.eql(u8, file.display_path, display_path)) return file.new;
        }
        return "(not planned)";
    }
};

/// The start of the settings Vicinae writes, comments included.
const settings_json =
    \\// This configuration is merged with the default vicinae configuration file.
    \\{
    \\   "font": {
    \\      "normal": {
    \\         "family": "Maple Mono Normal NFP",
    \\         "size": 13
    \\      }
    \\   },
    \\   "theme": {
    \\      "dark": {
    \\         "name": "Ricer",
    \\         "icon_theme": "Ricer"
    \\      }
    \\   }
    \\}
    \\
;

const test_theme = kosm.Theme.from(.{ .black = kosm.hex("041c26"), .white = kosm.hex("a3c5cc"), .cyan = kosm.hex("2d8699") }, .dark);

test "the theme is written whole without empty sections, then selected with the font" {
    var fixture: Fixture = undefined;
    try fixture.init(settings_json);
    defer fixture.deinit();
    var app = from(test_theme);
    app.font_family = "Iosevka";
    app.font_size = 12.5;
    try app.apply(&fixture.output);

    const written = fixture.planned("~/.local/share/vicinae/themes/kosm.toml");
    try testing.expect(std.mem.startsWith(u8, written,
        \\[meta]
        \\name = "kosm"
        \\description = "Generated by kosm"
        \\variant = "dark"
        \\
        \\[colors.core]
        \\accent = "#2d8699"
        \\accent_foreground = "#041c26"
        \\background = "#041c26"
        \\foreground = "#a3c5cc"
        \\
    ));
    try testing.expect(std.mem.indexOf(u8, written, "[colors.accents]\nblue = ") != null);
    try testing.expect(std.mem.indexOf(u8, written, "main_window") == null);
    try testing.expect(std.mem.indexOf(u8, written, "[colors.text.selection]\nbackground = \"#a3c5cc\"\nforeground = \"#041c26\"\n") != null);
    try testing.expect(std.mem.indexOf(u8, written, "[colors.list.item.selection]\n") != null);

    const settings = fixture.planned("~/.config/vicinae/settings.json");
    try testing.expect(std.mem.indexOf(u8, settings, "\"name\": \"kosm\",\n         \"icon_theme\": \"Ricer\"") != null);
    try testing.expect(std.mem.indexOf(u8, settings, "\"family\": \"Iosevka\",\n         \"size\": 12.5\n") != null);
    try testing.expect(std.mem.startsWith(u8, settings, "// This configuration"));
}

test "App{} writes only the meta, a light theme is selected under light, and a bad file fails" {
    var fixture: Fixture = undefined;
    try fixture.init(null);
    defer fixture.deinit();
    const empty: App = .{ .settings = null };
    try empty.apply(&fixture.output);
    try testing.expectEqualStrings("[meta]\nname = \"kosm\"\ndescription = \"Generated by kosm\"\nvariant = \"dark\"\n", fixture.planned("~/.local/share/vicinae/themes/kosm.toml"));

    var light: Fixture = undefined;
    try light.init(settings_json);
    defer light.deinit();
    const missing: App = .{ .meta = .{ .variant = .light } };
    try testing.expectError(error.NoMatch, missing.apply(&light.output));
    try testing.expectEqualStrings("~/.config/vicinae/settings.json", light.diagnostics.file);

    const wrong: App = .{ .file = "~/.local/share/vicinae/themes/kosm.json" };
    try testing.expectError(error.AppFailed, wrong.apply(&fixture.output));
    try testing.expectEqualStrings("Vicinae reads themes only from '.toml' files", fixture.diagnostics.message());
}
